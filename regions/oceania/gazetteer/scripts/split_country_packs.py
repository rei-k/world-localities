#!/usr/bin/env python3
"""Package each country independently; split archives into hash-checked parts."""
import argparse
import base64
from collections import defaultdict
import hashlib
import io
import json
from pathlib import Path
import zipfile


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def write_archive(root, folder, files, limit):
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, date_time=(2026, 9, 27, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, data)
    data = stream.getvalue()
    directory = root / folder
    directory.mkdir(parents=True, exist_ok=True)
    parts = []
    for i, offset in enumerate(range(0, len(data), limit), 1):
        part = data[offset:offset + limit]
        relative = folder + f'/part-{i:03}.b64'
        encoded = base64.b64encode(part) + b'\n'
        (root / relative).write_bytes(encoded)
        parts.append({'path': relative, 'storage_encoding': 'base64',
                      'stored_bytes': len(encoded), 'stored_sha256': sha256(encoded),
                      'bytes': len(part), 'sha256': sha256(part)})
    result = {'archive_bytes': len(data), 'archive_sha256': sha256(data), 'parts': parts,
              'members': {name: {'bytes': len(value), 'sha256': sha256(value)} for name, value in sorted(files.items())}}
    (directory / 'index.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    return result


def build(base, locale, root, limit):
    with zipfile.ZipFile(base) as archive:
        prefix = 'oceania_dataset_20260927/'
        base_files = {name[len(prefix):]: archive.read(name) for name in archive.namelist()
                      if name.startswith(prefix) and not name.endswith('/')}
    with zipfile.ZipFile(locale) as archive:
        locale_files = {name: archive.read(name) for name in archive.namelist() if not name.endswith('/')}
    countries = json.loads(base_files['countries.json'])
    by_cc = {c['country_code']: c for c in countries}
    entity_country = {c['id']: c['country_code'] for c in countries}
    country_files = defaultdict(dict)
    shared = {}
    for name, data in base_files.items():
        cc = None
        bits = name.split('/')
        if len(bits) >= 4 and bits[0] == 'data':
            cc = bits[2]
        elif len(bits) >= 3 and bits[0] == 'official':
            cc = bits[1]
        elif name.startswith('sources/geonames/') and bits[-1].split('.')[0] in by_cc:
            cc = bits[-1].split('.')[0]
        if cc in by_cc:
            country_files[cc]['base/' + name] = data
            if name.endswith('/places.jsonl'):
                for line in data.decode('utf-8').splitlines():
                    row = json.loads(line)
                    entity_country[row['id']] = cc
        else:
            shared['base/' + name] = data
    # Partition only JSONL rows; CSV exports below are regenerated by country.
    import csv
    for table in ('names', 'postal_links'):
        rows_by_country = defaultdict(list)
        for line in locale_files[table + '.jsonl'].decode('utf-8').splitlines():
            row = json.loads(line)
            rows_by_country[entity_country[row['entity_id']]].append(row)
        for cc in by_cc:
            rows = rows_by_country[cc]
            content = ''.join(json.dumps(row, ensure_ascii=False, separators=(',', ':')) + '\n' for row in rows)
            country_files[cc]['locale/' + table + '.jsonl'] = content.encode()
            stream = io.StringIO(newline='')
            if rows:
                writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
                writer.writeheader()
                writer.writerows(rows)
            country_files[cc]['locale/' + table + '.csv'] = ('\ufeff' + stream.getvalue()).encode()
    for name, data in locale_files.items():
        if name in {'names.jsonl', 'names.csv', 'postal_links.jsonl', 'postal_links.csv'}:
            continue
        cc = Path(name).name.split('.')[0]
        if name.startswith('sources/') and cc in by_cc:
            country_files[cc]['locale/' + name] = data
        else:
            shared['locale/' + name] = data
    index = {'schema_version': '1.0.0', 'max_part_bytes': limit,
             'base_archive_sha256': sha256(base.read_bytes()),
             'locale_archive_sha256': sha256(locale.read_bytes()),
             'base_snapshot': '2026-09-27', 'countries': {}}
    for cc, country in sorted(by_cc.items()):
        entry = write_archive(root, 'countries/' + cc, country_files[cc], limit)
        entry['places_member'] = f"base/data/{country['subregion']}/{cc}/places.jsonl"
        entry['subregion'] = country['subregion']
        entry['counts'] = {key: len(country_files[cc][member].decode('utf-8').splitlines()) for key, member in
                           [('places', entry['places_member']), ('names', 'locale/names.jsonl'), ('postal_links', 'locale/postal_links.jsonl')]}
        index['countries'][cc] = entry
    index['shared'] = write_archive(root, 'shared', shared, limit)
    (root / 'pack_manifest.json').write_text(json.dumps(index, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'countries': len(by_cc),
                      'parts': sum(len(e['parts']) for e in index['countries'].values()) + len(index['shared']['parts']),
                      'total_bytes': sum(e['archive_bytes'] for e in index['countries'].values()) + index['shared']['archive_bytes']}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--base', type=Path, required=True)
    parser.add_argument('--locale', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--part-bytes', type=int, default=524288)
    args = parser.parse_args()
    if args.part_bytes < 1024:
        parser.error('--part-bytes must be at least 1024')
    build(args.base, args.locale, args.output, args.part_bytes)
